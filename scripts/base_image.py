"""The base image tag: a hash of every file the base build reads.

docker/base.Dockerfile builds the heavy, rarely changing part of the RunPod image (CUDA
PyTorch stack, ComfyUI bake, baked node packs, SageAttention, onnxruntime-gpu, sam2,
llama-cpp-python). It is published as
ghcr.io/digitrgrs-eng/selfism-dashboard:base-<hash>; the app Dockerfile is FROM that
tag pinned by digest. A card-only change (catalog, workflows, launcher) does not change
the hash, so RunPod pulls only the small app layers.

  python scripts/base_image.py tag          print base-<hash>
  python scripts/base_image.py write-nodes  regenerate docker/base-nodes.json from the catalog
  python scripts/base_image.py check        exit 1 if base-nodes.json is stale
"""
import hashlib
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
REPOSITORY = 'ghcr.io/digitrgrs-eng/selfism-dashboard'
INPUTS = (
    'docker/base.Dockerfile',
    'docker/bake_comfyui.sh',
    'docker/install_llama_cpp.sh',
    'docker/base-constraints.txt',
    'docker/base-nodes.json',
)
NODES_FILE = ROOT / 'docker/base-nodes.json'


def baked_pack_names(root=ROOT):
    text = (root / 'docker/bake_comfyui.sh').read_text(encoding='utf-8')
    block = text.split('BAKED_NODE_PACKS=(', 1)[1].split(')', 1)[0]
    return re.findall(r'^\s*([A-Za-z0-9._-]+)\s*$', block, re.M)


def nodes_document(root=ROOT):
    """The catalog entries of the baked packs: all the bake reads from the catalog."""
    catalog = json.loads((root / 'catalog/selfism.json').read_text(encoding='utf-8'))
    nodes = {node['name']: node for node in catalog['nodes']}
    missing = [name for name in baked_pack_names(root) if name not in nodes]
    if missing:
        raise SystemExit('baked pack list is not in the catalog: ' + ', '.join(missing))
    document = {
        '_comment': 'Generated by scripts/base_image.py write-nodes from catalog/selfism.json. '
                    'The base build mounts this instead of the whole catalog.',
        'nodes': [nodes[name] for name in baked_pack_names(root)],
    }
    return json.dumps(document, indent=2, ensure_ascii=False) + '\n'


def base_hash(root=ROOT):
    digest = hashlib.sha256()
    for name in INPUTS:
        digest.update(name.encode() + b'\0')
        digest.update((root / name).read_bytes() + b'\0')
    return digest.hexdigest()[:16]


def base_tag(root=ROOT):
    return 'base-' + base_hash(root)


def main(argv):
    command = argv[1] if len(argv) > 1 else 'tag'
    if command == 'tag':
        print(base_tag())
    elif command == 'write-nodes':
        NODES_FILE.write_text(nodes_document(), encoding='utf-8')
        print('wrote', NODES_FILE.relative_to(ROOT), '->', base_tag())
    elif command == 'check':
        if NODES_FILE.read_text(encoding='utf-8') != nodes_document():
            raise SystemExit('docker/base-nodes.json is stale: run python scripts/base_image.py write-nodes')
        print('ok', base_tag())
    else:
        raise SystemExit(__doc__)


if __name__ == '__main__':
    main(sys.argv)
